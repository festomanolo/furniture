export type TKey = keyof typeof en;
const dicts: Record<Locale, Dict> = { en, sw };

export function translate(locale: Locale, key: TKey): string {
  return dicts[locale][key] ?? en[key];
}

/** Maps a zod error code (e.g. "phone_invalid") to a localized message. */
export function errorText(locale: Locale, code?: string): string | undefined {
  if (!code) return undefined;
  const k = `err_${code}` as TKey;
  return k in en ? translate(locale, k) : translate(locale, "err_required");
}

export function useT() {
  const locale = usePrefs((s) => s.locale);
  return { t: (key: TKey) => translate(locale, key), locale };
}
