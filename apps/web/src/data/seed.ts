const d = (fee: number | null, regions: string[], eta: [number, number], freeAbove?: number): DeliveryOption => ({
  method: "seller_delivery",
  fee: fee === null ? null : T(fee),
  regions,
  etaDays: eta,
  freeAbove: freeAbove ? T(freeAbove) : undefined,
});
const pickup: DeliveryOption = { method: "customer_collection", fee: T(0), regions: [], etaDays: [1, 2] };
