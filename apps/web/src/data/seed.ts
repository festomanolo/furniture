type Seed = Partial<Product> &
  Pick<Product, "slug" | "name" | "categoryId" | "sellerId" | "price" | "materials" | "colours" | "dimensions" | "description"> & {
    gallery: string[];
  };

let n = 0;
function product(s: Seed): Product {
  n += 1;
  const { gallery, ...rest } = s;
  return {
    id: `prd_${String(n).padStart(3, "0")}`,
    compareAtPrice: null,
    fulfilment: "ready_made",
    availability: "in_stock",
    productionDays: null,
    variants: [],
    delivery: [d(35000, dar, [1, 3], 1500000), pickup, transport],
    installation: { available: false, fee: null },
    warrantyMonths: 6,
    rating: 4.6,
    reviewCount: 18,
    soldCount: 40,
    tags: [],
    createdAt: new Date(Date.UTC(2026, 9, 30 - n)).toISOString(),
    ...rest,
    images: gallery.map((g, i) => ({ id: `img_${n}_${i}`, src: img(g), alt: `${s.name}${i ? ` view ${i + 1}` : ""}`, isPrimary: i === 0 })),
  };
}

